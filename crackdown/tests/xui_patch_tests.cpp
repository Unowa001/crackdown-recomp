// Host-only integrity tests. Synthetic inputs contain no game data.
#include "xui_patch.h"
#include "sha256.h"

#include <algorithm>
#include <fstream>
#include <iostream>
#include <iterator>
#include <limits>
#include <stdexcept>
#include <string>

namespace {
using Bytes = std::vector<uint8_t>;
void Require(bool value, const char* why) { if (!value) throw std::runtime_error(why); }
void BE(Bytes& bytes, uint64_t value, size_t count) {
  for (size_t i = count; i; --i) bytes.push_back(static_cast<uint8_t>(value >> (8 * (i - 1))));
}
void Digest(Bytes& out, const Bytes& data) {
  sha256::SHA256 hash;
  if (!data.empty()) hash.add(data.data(), data.size());
  auto hex = hash.getHash();
  for (size_t i = 0; i < hex.size(); i += 2)
    out.push_back(static_cast<uint8_t>(std::stoul(hex.substr(i, 2), nullptr, 16)));
}
Bytes Patch(const Bytes& old, const Bytes& result, const Bytes& ops, uint32_t count) {
  Bytes patch{'X','U','I','P','A','T','1',0};
  BE(patch, old.size(), 8); BE(patch, result.size(), 8);
  Digest(patch, old); Digest(patch, result); BE(patch, count, 4);
  patch.insert(patch.end(), ops.begin(), ops.end());
  return patch;
}
void Copy(Bytes& ops, uint64_t start, uint64_t size) {
  ops.push_back(0); BE(ops, start, 8); BE(ops, size, 8);
}
void Insert(Bytes& ops, const Bytes& data) {
  ops.push_back(1); BE(ops, data.size(), 8); ops.insert(ops.end(), data.begin(), data.end());
}
void Reject(const Bytes& old, const Bytes& patch) {
  bool failed = false;
  try { crackdown::ApplyXuiPatch(old, patch); } catch (const std::exception&) { failed = true; }
  Require(failed, "invalid patch accepted");
}
Bytes Read(const char* path) {
  std::ifstream file(path, std::ios::binary);
  if (!file) throw std::runtime_error("cannot open fixture");
  return Bytes(std::istreambuf_iterator<char>(file), {});
}
}  // namespace

int main(int argc, char** argv) {
  try {
    const Bytes old{'a', 'b', 'c', 'd', 'e', 'f'};
    const Bytes result{'e','f','N',0,255,'a','b','e','f'};
    Bytes ops;
    Copy(ops, 4, 2); Insert(ops, {'N',0,255}); Copy(ops, 0, 2); Copy(ops, 4, 2);
    const auto patch = Patch(old, result, ops, 4);
    Require(crackdown::ApplyXuiPatch(old, patch) == result, "COPY/INSERT roundtrip");
    Require(crackdown::ApplyXuiPatch({}, Patch({}, {}, {}, 0)).empty(), "empty result");
    for (size_t i = 0; i < patch.size(); ++i) Reject(old, Bytes(patch.begin(), patch.begin() + i));
    auto bad = patch; bad.push_back(0); Reject(old, bad);
    bad = patch; bad[0] ^= 1; Reject(old, bad);
    bad = patch; bad[24] ^= 1; Reject(old, bad);
    bad = patch; bad[56] ^= 1; Reject(old, bad);
    bad = patch; bad[92] = 9; Reject(old, bad);
    bad = patch; std::fill(bad.begin()+88, bad.begin()+92, 255); Reject(old, bad);
    Reject({'x','b','c','d','e','f'}, patch);
    for (auto [offset, size] : {std::pair<uint64_t,uint64_t>{6,1}, {0,0}, {0,7},
                               {std::numeric_limits<uint64_t>::max(),1}, {0,std::numeric_limits<uint64_t>::max()}}) {
      Bytes invalid; Copy(invalid, offset, size); Reject(old, Patch(old, {'x'}, invalid, 1));
    }
    Bytes invalid; Insert(invalid, {'a','b'}); Reject(old, Patch(old, {'a'}, invalid, 1));
    invalid = {1}; BE(invalid, std::numeric_limits<uint64_t>::max(), 8);
    Reject(old, Patch(old, {'a'}, invalid, 1));
    Reject(old, Patch(old, {'a'}, {}, 0));
    bad = patch; std::fill(bad.begin()+16, bad.begin()+24, 255); Reject(old, bad);
    // Optional local fixture checks Python-generated bytes against this decoder.
    // Never distribute or commit the original/result game packages.
    if (argc == 4) {
      Require(crackdown::ApplyXuiPatch(Read(argv[1]), Read(argv[2])) == Read(argv[3]), "Python/C++ parity");
      std::cout << "Python/C++ fixture parity passed\n";
    } else Require(argc == 1, "usage: xui_patch_tests [ORIGINAL PATCH RESULT]");
    std::cout << "XUIPAT1 integrity tests passed\n";
    return 0;
  } catch (const std::exception& error) {
    std::cerr << error.what() << '\n';
    return 1;
  }
}
